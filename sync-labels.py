#!/usr/bin/env python3
"""
sync-labels.py -- cross-document references for imsart, which forbids xr/xr-hyper.

Reads the .aux of each document and writes the other's labels into its preamble
as prefixed \newlabel entries: main's labels appear in the supplement as M-<label>,
the supplement's appear in main as S-<label>.

Usage, from the directory holding the sources:

    pdflatex marginfx-main
    pdflatex marginfx-supp
    python3 sync-labels.py
    pdflatex marginfx-main
    pdflatex marginfx-supp

Run it again whenever a numbered result is added, removed, or reordered.
"""

import re
import sys
from pathlib import Path

MAIN = "marginfx-main"
SUPP = "marginfx-supp"
MARKER = "%%__EXTLABELS__"

# \newlabel{name}{{number}{page}{title}{anchor}{}}  -- brace-matched, not regexed
NEWLABEL = re.compile(r"\\newlabel\{")


def read_labels(aux_path):
    """Return the raw \newlabel lines from an .aux file, keyed by label name."""
    text = aux_path.read_text(encoding="utf-8", errors="replace")
    out = {}
    for m in NEWLABEL.finditer(text):
        start = m.end()
        depth = 1
        i = start
        while i < len(text) and depth:
            if text[i] == "{":
                depth += 1
            elif text[i] == "}":
                depth -= 1
            i += 1
        name = text[start:i - 1]
        # the value group follows immediately
        if i >= len(text) or text[i] != "{":
            continue
        j = i + 1
        depth = 1
        while j < len(text) and depth:
            if text[j] == "{":
                depth += 1
            elif text[j] == "}":
                depth -= 1
            j += 1
        value = text[i:j]
        if "@" in name or name.startswith("sub@"):
            continue
        out[name] = value
    return out


def split_groups(value):
    """Split a brace-delimited value like {{a}{b}{c}} into its top-level groups."""
    if not value.startswith("{") or not value.endswith("}"):
        return None
    inner = value[1:-1]
    groups, i = [], 0
    while i < len(inner):
        if inner[i] != "{":
            return None
        depth, j = 1, i + 1
        while j < len(inner) and depth:
            if inner[j] == "{":
                depth += 1
            elif inner[j] == "}":
                depth -= 1
            j += 1
        if depth:
            return None
        groups.append(inner[i + 1:j - 1])
        i = j
    return groups


def build_block(labels, prefix):
    """Rebuild each entry from its number and page only.

    Copying the raw .aux value verbatim is fragile: hyperref writes five fields
    with nested braces, and any mismatch leaks stray text into the document.
    Only the first two fields are needed for \\ref and \\pageref.
    """
    lines = [MARKER + "  <- generated by sync-labels.py; do not edit by hand",
             "\\makeatletter"]
    skipped = 0
    for name in sorted(labels):
        groups = split_groups(labels[name])
        if not groups or len(groups) < 2:
            skipped += 1
            continue
        number, page = groups[0], groups[1]
        title = groups[2] if len(groups) > 2 else ""
        anchor = groups[3] if len(groups) > 3 else ""
        if "\\" in number and "\\relax" in number:
            skipped += 1
            continue
        lines.append("\\newlabel{%s-%s}{{%s}{%s}{%s}{%s}{}}"
                     % (prefix, name, number, page, title, anchor))
    lines.append("\\makeatother")
    if skipped:
        print("  skipped %d malformed entries" % skipped)
    return "\n".join(lines)


def splice(tex_path, block):
    text = tex_path.read_text(encoding="utf-8")
    lines = text.split("\n")
    try:
        start = next(i for i, l in enumerate(lines) if l.startswith(MARKER))
    except StopIteration:
        sys.exit("No %s marker found in %s" % (MARKER, tex_path))
    end = next(i for i, l in enumerate(lines[start:], start)
               if l.strip() == "\\makeatother")
    lines[start:end + 1] = block.split("\n")
    tex_path.write_text("\n".join(lines), encoding="utf-8")


def main():
    here = Path(".")
    main_aux, supp_aux = here / (MAIN + ".aux"), here / (SUPP + ".aux")
    for p in (main_aux, supp_aux):
        if not p.exists():
            sys.exit("Missing %s -- compile both documents once first." % p)

    main_labels = read_labels(main_aux)
    supp_labels = read_labels(supp_aux)

    splice(here / (SUPP + ".tex"), build_block(main_labels, "M"))
    splice(here / (MAIN + ".tex"), build_block(supp_labels, "S"))

    print("Wrote %d M- labels into %s.tex" % (len(main_labels), SUPP))
    print("Wrote %d S- labels into %s.tex" % (len(supp_labels), MAIN))
    print("Now recompile both documents.")


if __name__ == "__main__":
    main()
